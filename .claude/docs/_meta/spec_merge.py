#!/usr/bin/env python3
"""Слияние дельты изменения в спеку домена.

Пока слияние делалось руками — «обнови все строки таблицы, ни одной не
пропуская» — проверить его было нечем: пропущенную строку замечали через месяц,
когда автор изменения уже забыл подробности. Здесь оно становится кодом.

Порядок разделов важен и он не наш произвол:

1. **Переименовано** — первым, иначе следующие разделы ищут требование по
   старому идентификатору и не находят.
2. **Удалено** — вырезается по идентификатору.
3. **Изменено** — блок заменяется целиком, вместе с уцелевшими сценариями.
4. **Добавлено** — дописывается в конец раздела требований.

Слияние перезапускаемо. Требование из «Добавлено», уже стоящее в спеке с тем же
текстом, считается слитым; «Удалено», которого уже нет, — тоже. А вот совпадение
по идентификатору при разном содержимом — конфликт: молча затирать чужую правку
нельзя, потому что вторая правка того же требования обычно означает, что двое
делали одно и то же, не зная друг о друге.

Запуск:
    python3 .claude/docs/_meta/spec_merge.py <spec.md> <delta.md> [--dry-run]
"""
import re
import sys
from pathlib import Path

ЗАГОЛОВОК = re.compile(r"^###\s+Requirement:\s*(.+?)\s*$", re.MULTILINE)
ИДЕНТИФИКАТОР = re.compile(r"^\*\*ID\*\*:\s*(\S+)\s*$", re.MULTILINE)
РАЗДЕЛЫ = ("## Добавлено", "## Изменено", "## Удалено", "## Переименовано")


def раздел(source, имя):
    """Кусок дельты от заголовка раздела до следующего раздела."""
    if имя not in source:
        return ""

    хвост = source.split(имя, 1)[1]

    for следующий in РАЗДЕЛЫ:
        if следующий != имя and следующий in хвост:
            хвост = хвост.split(следующий, 1)[0]

    return хвост


def блоки(текст):
    """Требования как куски текста: от «### Requirement:» до следующего заголовка.

    Работаем с сырым текстом, а не с разобранной моделью: спека вливается
    обратно в файл, и любой разбор-сборка теряет то, чего модель не знает —
    комментарии, порядок полей, пустые строки автора.
    """
    out = []
    места = [m.start() for m in ЗАГОЛОВОК.finditer(текст)]

    for i, старт in enumerate(места):
        конец = len(текст)

        for граница in места[i + 1:] + [len(текст)]:
            конец = граница
            break

        # Раздел верхнего уровня обрывает требование раньше следующего «###».
        следующий_раздел = текст.find("\n## ", старт)

        if 0 <= следующий_раздел < конец:
            конец = следующий_раздел + 1

        кусок = текст[старт:конец]
        ident = ИДЕНТИФИКАТОР.search(кусок)
        out.append((ident.group(1) if ident else None, старт, конец, кусок))

    return out


def без_служебного(кусок):
    """Строка «Что изменилось» адресована ревьюеру и в спеку не переезжает."""
    строки = [s for s in кусок.splitlines() if not s.startswith("**Что изменилось:**")]
    return "\n".join(строки).rstrip() + "\n"


def слить(спека, дельта):
    заметки, поломки = [], []
    текст = спека

    # 1. Переименование — первым.
    переименование = раздел(дельта, "## Переименовано")
    froms = re.findall(r"^-\s*FROM:\s*`?(\S+?)`?\s*$", переименование, re.MULTILINE)
    tos = re.findall(r"^-\s*TO:\s*`?(\S+?)`?\s*$", переименование, re.MULTILINE)

    for источник, цель in zip(froms, tos):
        if f"**ID**: {источник}" in текст:
            текст = текст.replace(f"**ID**: {источник}", f"**ID**: {цель}")
            заметки.append(f"переименовано: {источник} → {цель}")
        elif f"**ID**: {цель}" in текст:
            заметки.append(f"уже слито: переименование {источник} → {цель}")
        else:
            поломки.append(f"переименовывать нечего: «{источник}» в спеке нет")

    # 2. Удаление.
    for ident in re.findall(r"^###\s+(\S+/\S+)\s*$", раздел(дельта, "## Удалено"), re.MULTILINE):
        найдено = [b for b in блоки(текст) if b[0] == ident]

        if not найдено:
            заметки.append(f"уже слито: {ident} в спеке нет")
            continue

        _, старт, конец, _ = найдено[0]
        текст = (текст[:старт] + текст[конец:]).replace("\n\n\n", "\n\n")
        заметки.append(f"удалено: {ident}")

    # 3. Изменение — замена блока целиком.
    for ident, _, _, новый in блоки(раздел(дельта, "## Изменено")):
        if ident is None:
            поломки.append("в «Изменено» требование без поля **ID**")
            continue

        найдено = [b for b in блоки(текст) if b[0] == ident]

        if not найдено:
            поломки.append(f"конфликт: «{ident}» — такого требования в спеке нет")
            continue

        _, старт, конец, старый = найдено[0]
        новый = без_служебного(новый)

        if старый.strip() == новый.strip():
            заметки.append(f"уже слито: {ident}")
            continue

        текст = текст[:старт] + новый + "\n" + текст[конец:]
        заметки.append(f"изменено: {ident}")

    # 4. Добавление — в конец раздела требований.
    for ident, _, _, новый in блоки(раздел(дельта, "## Добавлено")):
        if ident is None:
            поломки.append("в «Добавлено» требование без поля **ID**")
            continue

        найдено = [b for b in блоки(текст) if b[0] == ident]
        новый = без_служебного(новый)

        if найдено:
            if найдено[0][3].strip() == новый.strip():
                заметки.append(f"уже слито: {ident}")
            else:
                поломки.append(
                    f"конфликт: «{ident}» уже есть в спеке, но с другим текстом — "
                    "похоже, требование правили дважды"
                )

            continue

        текст = текст.rstrip() + "\n\n" + новый
        заметки.append(f"добавлено: {ident}")

    return текст, заметки, поломки


if __name__ == "__main__":
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]

    if len(аргументы) != 2:
        sys.exit(__doc__)

    спека_путь, дельта_путь = Path(аргументы[0]), Path(аргументы[1])
    итог, заметки, поломки = слить(
        спека_путь.read_text(encoding="utf-8"),
        дельта_путь.read_text(encoding="utf-8"),
    )

    if поломки:
        print("spec_merge — слияние не выполнено:", file=sys.stderr)

        for поломка in поломки:
            print(f"  {поломка}", file=sys.stderr)

        print(
            "\nРазбери конфликт руками: спека и дельта разошлись сильнее, "
            "чем можно свести механически.",
            file=sys.stderr,
        )
        sys.exit(1)

    if "--dry-run" not in sys.argv:
        спека_путь.write_text(итог, encoding="utf-8")

    for заметка in заметки:
        print(f"  {заметка}")

    print(f"spec_merge — {спека_путь.name}: изменений {len(заметки)}")
